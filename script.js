let gender = "male";
let playerName = "Герой";

function startGame(g) {
  const nameInput = document.getElementById("player-name");
  const rawName = nameInput.value.trim();
  playerName =
    rawName.length > 0 ? rawName : g === "male" ? "Герой" : "Героиня";

  gender = g;
  resetState();
  document.getElementById("title-screen").style.display = "none";
  showNode("start");
}

function showNode(id) {
  const node = story[id];
  if (!node) return;

  const fade = document.getElementById("fade");
  fade.style.opacity = "1";

  setTimeout(() => {
    document.getElementById("bg").style.backgroundImage = `url('${node.bg}')`;

    const text = typeof node.text === "function" ? node.text() : node.text;
    document.getElementById("story").textContent = text;

    const choicesDiv = document.getElementById("choices");
    choicesDiv.innerHTML = "";

    node.choices.forEach((choice) => {
      const btn = document.createElement("button");
      btn.className = "choice-btn";
      btn.textContent =
        typeof choice.text === "function" ? choice.text() : choice.text;
      btn.onclick = () => {
        if (typeof choice.effect === "function") {
          choice.effect();
        }
        showNode(choice.next);
      };
      choicesDiv.appendChild(btn);
    });

    fade.style.opacity = "0";
  }, 400);
}
